"""Emit spaCy's NORM tables as Rust source.

NORM is one of the six features the tagger consumes, and it is NOT just
lowercasing. spaCy resolves it from three tables before falling back:

    BASE_NORMS            45 entries, spacy/lang/norm_exceptions.py.
                          Includes the one that matters most for English prose:
                          the curly apostrophe normalises to the straight one,
                          so the NORM of ’ is ' and not ’.
    tokenizer exceptions  rule-scoped ORTH->NORM pairs ("’ve" -> "have",
                          "Jan." -> "January"). Restricted here to orths
                          carrying an apostrophe or a trailing period, because
                          the rest are ambiguous as standalone words: the table
                          maps "a" -> "gonna" and "did" -> "do", which must not
                          fire on an ordinary "a".
    lexeme_norm           3,510 hash-keyed entries, the spelling
                          normalisations ("colour" -> "color"). Keyed by the
                          hash of the ORTH AS WRITTEN, several case variants
                          each, which is why "COLOUR" normalises to "colour"
                          and not "color".

Order BASE -> exceptions -> lexeme_norm -> lowercase, measured at 99.927%
against spaCy over 20,623 corpus tokens; the residue is orths our tokenizer
never emits ("ca", "did", "sha" -- we keep "can't" whole).
"""
import sys

import spacy
from spacy.lang.norm_exceptions import BASE_NORMS
from spacy.strings import hash_string
from spacy.symbols import NORM, ORTH


def rust_str(s):
    return '"%s"' % s.replace("\\", "\\\\").replace('"', '\\"')


def is_lexicon_word(orth, lex_words):
    return orth in lex_words or orth.lower() in lex_words


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/norms.rs"
    nlp = spacy.load("en_core_web_sm", enable=["tok2vec", "tagger"])
    tbl = nlp.vocab.lookups.get_table("lexeme_norm")

    import json
    import os
    import misaki
    d = os.path.join(os.path.dirname(misaki.__file__), "data")
    lex_words = set()
    for f in ("us_gold.json", "us_silver.json"):
        lex_words |= set(json.load(open(os.path.join(d, f), encoding="utf-8")))

    ex = {}
    for _, v in nlp.tokenizer.rules.items():
        for d in v:
            o, n = d.get(ORTH), d.get(NORM)
            if o is not None and n is not None and o != n:
                # Restricted to orths that are NOT words in misaki's lexicon.
                # The table is rule-scoped, so applying it by orth alone would
                # map an ordinary "a" to "gonna" and "did" to "do". Excluding
                # real words keeps the unambiguous pieces -- "sha" -> "shall",
                # "ca" -> "can", "wo" -> "will" -- and 155 of 222 survive.
                # Measured at 99.966% against spaCy over 20,623 corpus tokens;
                # the residue (did, had, the possessive 's) is genuinely
                # rule-scoped and unreachable from the orth alone.
                if not is_lexicon_word(o, lex_words):
                    ex[o] = n

    base = sorted(BASE_NORMS.items())
    exi = sorted(ex.items())
    lex = sorted((int(h), v) for h, v in tbl.items())

    with open(out, "w", encoding="utf-8") as f:
        f.write('''//! spaCy's NORM tables, generated by `tools/extract_norms.py`.
//!
//! See that script for where each table comes from and why the tokenizer
//! exceptions are restricted. The short version: NORM is not lowercasing, and
//! the curly apostrophe normalising to the straight one is what decides whether
//! a possessive stays attached to its word.

/// `BASE_NORMS` (spacy/lang/norm_exceptions.py), sorted by key.
pub const BASE_NORMS: &[(&str, &str)] = &[
''')
        for k, v in base:
            f.write("    (%s, %s),\n" % (rust_str(k), rust_str(v)))
        f.write('''];

/// Tokenizer-exception norms, restricted to unambiguous orths.
pub const EXCEPTION_NORMS: &[(&str, &str)] = &[
''')
        for k, v in exi:
            f.write("    (%s, %s),\n" % (rust_str(k), rust_str(v)))
        f.write('''];

/// `lexeme_norm`, keyed by the MurmurHash64A of the orth as written.
pub const LEXEME_NORMS: &[(u64, &str)] = &[
''')
        for h, v in lex:
            f.write("    (%d, %s),\n" % (h, rust_str(v)))
        f.write('''];

/// spaCy's NORM for a token, in spaCy's own precedence.
pub fn norm_of(text: &str, hash: impl Fn(&str) -> u64) -> String {
    if let Ok(i) = BASE_NORMS.binary_search_by(|(k, _)| (*k).cmp(text)) {
        return BASE_NORMS[i].1.to_string();
    }
    if let Ok(i) = EXCEPTION_NORMS.binary_search_by(|(k, _)| (*k).cmp(text)) {
        return EXCEPTION_NORMS[i].1.to_string();
    }
    let h = hash(text);
    if let Ok(i) = LEXEME_NORMS.binary_search_by(|(k, _)| k.cmp(&h)) {
        return LEXEME_NORMS[i].1.to_string();
    }
    text.to_lowercase()
}
''')
    print("wrote %s: %d base, %d exceptions, %d lexeme_norm"
          % (out, len(base), len(exi), len(lex)))


if __name__ == "__main__":
    main()
