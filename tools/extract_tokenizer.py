"""Emit spaCy's English tokenizer patterns and exceptions as Rust source.

misaki tokenizes with spaCy and then subtokenizes within each spaCy token, and
its word-grouping rule reads the TAG of a spaCy token. So reproducing spaCy's
tokenization is what lets the grouping be exact.

Three pattern sets and one exception table, read off the live tokenizer's
COMPILED searchers so they cannot drift from what spaCy actually uses:

  prefix_search / suffix_search  anchored alternations, applied by peeling
  infix_finditer                 splits what survives the peeling
  rules                          1,347 special cases

Each exception piece carries its ORTH and, when the rule sets one, its NORM.
The norm has to travel with the RULE: rule["you'd"] gives the second piece the
norm "'d", while another rule gives the same orth the norm "would". An
orth-keyed table cannot tell them apart and picks one arbitrarily, which made
the tagger call the second piece of "you'd" an MD where spaCy says ''.

The patterns carry large Unicode character classes (currency, icons), so they
are written as raw strings rather than rebuilt.
"""
import sys

import spacy
from spacy.symbols import NORM, ORTH


def rust_raw(pat):
    n = 1
    while ('"' + "#" * n) in pat:
        n += 1
    h = "#" * n
    return 'r%s"%s"%s' % (h, pat, h)


def lit(x):
    return '"%s"' % x.replace("\\", "\\\\").replace('"', '\\"')


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/spacy_tokenizer_data.rs"
    nlp = spacy.load("en_core_web_sm", enable=["tok2vec", "tagger"])
    tk = nlp.tokenizer

    prefix = tk.prefix_search.__self__.pattern
    suffix = tk.suffix_search.__self__.pattern
    infix = tk.infix_finditer.__self__.pattern
    url = tk.url_match.__self__.pattern if tk.url_match else None

    rules = {}
    for k, v in tk.rules.items():
        pieces = [(d.get(ORTH), d.get(NORM)) for d in v]
        if all(o is not None for o, _ in pieces):
            rules[k] = pieces

    with open(out, "w", encoding="utf-8") as f:
        f.write("//! spaCy's English tokenizer patterns and exceptions, generated by\n")
        f.write("//! `tools/extract_tokenizer.py`. See that script for why this is needed.\n")
        f.write("//!\n")
        f.write("//! Read off the live tokenizer's compiled searchers, so they cannot drift\n")
        f.write("//! from what spaCy actually uses.\n\n")
        f.write("/// Anchored alternation matching a prefix to peel off the front.\n")
        f.write("pub const PREFIX_PATTERN: &str = %s;\n\n" % rust_raw(prefix))
        f.write("/// Anchored alternation matching a suffix to peel off the end.\n")
        f.write("pub const SUFFIX_PATTERN: &str = %s;\n\n" % rust_raw(suffix))
        f.write("/// Matches inside what survives the peeling; each match is a split point.\n")
        f.write("pub const INFIX_PATTERN: &str = %s;\n" % rust_raw(infix))
        if url:
            f.write("\n/// A whole-token URL match, which short-circuits all peeling.\n")
            f.write("pub const URL_PATTERN: &str = %s;\n" % rust_raw(url))
        f.write("\n/// spaCy's tokenizer exceptions. The key is matched as a whole token and\n")
        f.write("/// expands to these (orth, norm) pieces; norm is None when the rule sets\n")
        f.write("/// none. Sorted by key so the lookup can binary-search.\n")
        f.write("pub const EXCEPTIONS: &[(&str, &[(&str, Option<&str>)])] = &[\n")
        for k in sorted(rules):
            ps = ", ".join(
                "(%s, %s)" % (lit(o), ("Some(%s)" % lit(n)) if n is not None else "None")
                for o, n in rules[k]
            )
            f.write("    (%s, &[%s]),\n" % (lit(k), ps))
        f.write("];\n")

    print("wrote %s" % out)
    print("  prefix %d chars, suffix %d, infix %d" % (len(prefix), len(suffix), len(infix)))
    print("  %d exceptions" % len(rules))


if __name__ == "__main__":
    main()
