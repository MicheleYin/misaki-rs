"""Generate src/unicode_numeric_data.rs from Python unicodedata.

Mirrors misaki's Lexicon.numeric_if_needed / isdigit checks:

    if not c.isdigit():
        return c
    n = unicodedata.numeric(c)
    return str(int(n)) if n == int(n) else c

Also emits `is_digit` matching Python `str.isdigit()` for one character.
"""
from __future__ import annotations

import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src" / "unicode_numeric_data.rs"


def main() -> None:
    numeric_rows: list[tuple[int, str]] = []
    digit_cps: list[int] = []
    for cp in range(0x110000):
        c = chr(cp)
        if not c.isdigit():
            continue
        digit_cps.append(cp)
        n = unicodedata.numeric(c)
        if n == int(n):
            numeric_rows.append((cp, str(int(n))))

    lines: list[str] = [
        "//! Generated by tools/extract_numeric.py — do not edit by hand.",
        "//! Python `str.isdigit()` / `unicodedata.numeric` for misaki Lexicon.__call__.",
        "",
        "/// Sorted codepoints where Python `str.isdigit()` is true.",
        "const IS_DIGIT: &[u32] = &[",
    ]
    chunk = 12
    for i in range(0, len(digit_cps), chunk):
        part = ", ".join(str(cp) for cp in digit_cps[i : i + chunk])
        lines.append(f"    {part},")
    lines.extend(
        [
            "];",
            "",
            "/// Sorted `(codepoint, ascii_digit)` for integer-valued `unicodedata.numeric`.",
            "const NUMERIC_MAP: &[(u32, &str)] = &[",
        ]
    )
    for cp, s in numeric_rows:
        lines.append(f'    ({cp}, "{s}"),')
    alpha_cps = [cp for cp in range(0x110000) if chr(cp).isalpha()]
    lines.extend(
        [
            "];",
            "",
            "/// Map a Unicode scalar to its ASCII digit string when Python",
            "/// `c.isdigit()` and `unicodedata.numeric(c)` is an integer.",
            "pub fn numeric_if_needed(c: char) -> Option<&'static str> {",
            "    let cp = c as u32;",
            "    NUMERIC_MAP",
            "        .binary_search_by_key(&cp, |&(k, _)| k)",
            "        .ok()",
            "        .map(|i| NUMERIC_MAP[i].1)",
            "}",
            "",
            "/// Python `str.isdigit()` for a single character.",
            "pub fn is_digit(c: char) -> bool {",
            "    IS_DIGIT.binary_search(&(c as u32)).is_ok()",
            "}",
            "",
            "/// Sorted codepoints where Python `str.isalpha()` is true.",
            "const IS_ALPHA: &[u32] = &[",
        ]
    )
    for i in range(0, len(alpha_cps), chunk):
        part = ", ".join(str(cp) for cp in alpha_cps[i : i + chunk])
        lines.append(f"    {part},")
    lines.extend(
        [
            "];",
            "",
            "/// Python `str.isalpha()` for a single character.",
            "pub fn is_alpha(c: char) -> bool {",
            "    IS_ALPHA.binary_search(&(c as u32)).is_ok()",
            "}",
            "",
        ]
    )
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(
        f"wrote {OUT} ({len(numeric_rows)} numeric, {len(digit_cps)} isdigit, {len(alpha_cps)} isalpha)"
    )


if __name__ == "__main__":
    main()
