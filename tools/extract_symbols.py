"""Emit spaCy's StringStore symbol table as Rust source.

spaCy's StringStore does not hash every string. It carries a fixed table of 457
symbols whose IDs are small integers, and `get_string_id` returns that ID
instead of the MurmurHash. The shape `X` is symbol 101, so a one-character
uppercase token's SHAPE feature is 101 and not its hash -- hashing it anyway
shifted the feature and cost ~0.7% of tags.
"""
import sys

from spacy.symbols import IDS


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/symbols.rs"
    items = sorted(IDS.items(), key=lambda kv: kv[0])
    with open(out, "w", encoding="utf-8") as f:
        f.write('''//! spaCy's StringStore symbol table, generated by `tools/extract_symbols.py`.
//!
//! `get_string_id` returns a fixed small ID for any string in this table and
//! the MurmurHash64A otherwise. Sorted by key so the lookup can binary-search.

/// (symbol, id) pairs, sorted by symbol.
pub const SYMBOLS: &[(&str, u64)] = &[
''')
        for k, v in items:
            f.write('    (%s, %d),\n' % (('r#"%s"#' % k) if '"' in k or '\\' in k else '"%s"' % k, v))
        f.write(''']; 

/// spaCy's `get_string_id`: the symbol ID when the string is a known symbol,
/// otherwise the MurmurHash64A of its UTF-8 bytes with seed 1.
pub fn string_id(s: &str, hash: impl Fn(&str) -> u64) -> u64 {
    match SYMBOLS.binary_search_by(|(k, _)| (*k).cmp(s)) {
        Ok(i) => SYMBOLS[i].1,
        Err(_) => hash(s),
    }
}
''')
    print("wrote %s with %d symbols" % (out, len(items)))


if __name__ == "__main__":
    main()
